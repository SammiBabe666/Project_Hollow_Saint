#!/usr/bin/env python3
"""Write the Opus 2 build's generated headers (opus/sammi.hollow_saint):

    hs_svg.h   plugin/hollow_saint/hollow_saint.svg as a C string (opus_art_text writes it to the plugin's folder)
    hs_sine.h  the sine table hollow_saint.c reads: round(32767 sin(2 pi i / 8192)), i = 0 .. 8191 (the same values as
               the firmware's table at 0x0101E5E8, which the kennel build reads; checked against tests/bfin_sim/tables.h)

    python3 tools/gen_opus_headers.py [--check]     --check: fail if the committed headers are not current

Copyright (C) 2026 the hollow_saint authors. GPL-3.0-or-later with the OP-1 firmware permission.
"""
import math, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'opus', 'sammi.hollow_saint')
SVG = os.path.join(ROOT, 'plugin', 'hollow_saint', 'hollow_saint.svg')
SIM = os.path.join(ROOT, 'tests', 'bfin_sim', 'tables.h')


def sine():
    t = [round(32767 * math.sin(2 * math.pi * i / 8192)) for i in range(8192)]
    m = re.search(r'SIM_SINE\[8192\] = \{([^}]*)\}', open(SIM).read())
    if [int(x) for x in m.group(1).split(',')] != t:
        sys.exit('hs_sine: differs from the firmware table in tests/bfin_sim/tables.h')
    rows = [', '.join(map(str, t[i:i + 16])) for i in range(0, 8192, 16)]
    return ('/* generated by tools/gen_opus_headers.py: round(32767 sin(2 pi i / 8192)), as the firmware\'s table */\n'
            'const int16_t hs_sine[8192] = {\n    ' + ',\n    '.join(rows) + '\n};\n')


def svg():
    text = open(SVG, encoding='utf-8').read()
    lines = []
    for line in text.splitlines(keepends=True):
        lines.append('"' + line.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"')
    return ('/* generated by tools/gen_opus_headers.py from plugin/hollow_saint/hollow_saint.svg */\n'
            'static const char HS_SVG[] =\n' + '\n'.join(lines) + ';\n')


def main():
    check = '--check' in sys.argv[1:]
    stale = []
    for name, text in (('hs_sine.h', sine()), ('hs_svg.h', svg())):
        path = os.path.join(OUT, name)
        old = open(path, encoding='utf-8').read() if os.path.isfile(path) else None
        if old == text:
            continue
        if check:
            stale.append(name)
        else:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print(f'wrote {os.path.relpath(path, ROOT)}')
    if stale:
        sys.exit('not current (run tools/gen_opus_headers.py): ' + ', '.join(stale))


if __name__ == '__main__':
    main()
